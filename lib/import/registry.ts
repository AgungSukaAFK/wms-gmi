const partNumber = (extra: Partial<ImportColumn> = {}): ImportColumn => ({
  key: "part_number",
  header: "Part Number",
  type: "text",
  required: true,
  description:
    "Part number sesuai master Barang. Huruf besar/kecil & spasi tepi diabaikan; beda spasi/titik/strip dicocokkan ke barang yang mirip kalau kandidatnya cuma satu.",
  example: "14L-0184-1",
  width: 20,
  ...extra,
});

const gudang = (key: string, header: string, description: string, extra: Partial<ImportColumn> = {}): ImportColumn => ({
  key,
  header,
  type: "text",
  ref: "cabang",
  description: `${description} Isi persis nama gudang di master Cabang (lihat dropdown / sheet Daftar).`,
  example: "GMI-JAKARTA",
  width: 20,
  ...extra,
});

const tanggal = (key: string, header: string, description: string, extra: Partial<ImportColumn> = {}): ImportColumn => ({
  key,
  header,
  type: "date",
  description: `${description} Format tanggal Excel atau teks DD/MM/YYYY.`,
  example: "24/10/2026",
  width: 14,
  ...extra,
});

const modeOption = (normalDesc: string, riwayatDesc: string): ImportOption => ({
  key: "mode",
  type: "select",
  label: "Mode proses",
  choices: [
    { value: "normal", label: "Normal (alur approval)", description: normalDesc },
    { value: "riwayat", label: "Riwayat (langsung selesai)", description: riwayatDesc },
  ],
  default: "normal",
});

