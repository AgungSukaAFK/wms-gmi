-- ============================================================
-- 4. Link DO Reguler <- SO (opsional; DO Reguler tanpa SO tetap boleh)
-- ============================================================
ALTER TABLE public.do_reguler
  ADD COLUMN IF NOT EXISTS so_id BIGINT REFERENCES public.so_reguler(id);

ALTER TABLE public.do_reguler_items
  ADD COLUMN IF NOT EXISTS so_item_id BIGINT REFERENCES public.so_reguler_items(id),
  -- Bagian qty DO ini yang dihitung memakai barang hasil PO-dari-SO yang
  -- SUDAH diterima (sisanya = dari stok biasa). Dicatat saat DO dibuat karena
  -- urutan kejadian menentukan: "DO 2 dari stok lalu PO 3" vs "PO 3 diterima
  -- lalu DO 2" punya total yang sama tapi sisa yang boleh di-PO berbeda.
  ADD COLUMN IF NOT EXISTS qty_from_po INTEGER NOT NULL DEFAULT 0 CHECK (qty_from_po >= 0);

