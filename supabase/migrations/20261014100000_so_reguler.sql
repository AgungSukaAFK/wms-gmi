-- Migration: SO Reguler (Sales Order reguler ke customer)
-- Date: 2026-10-14
-- Description:
--   Dokumen Sales Order reguler (non-consignment). Input mirip Material Request
--   (kode manual, tanggal, deadline, kategori, prioritas & catatan per item)
--   tapi TANPA approval, wajib customer, dan lokasi site default cabang user
--   (boleh diganti).
--
--   Alur pemenuhan per item, dinamis & partial per qty:
--     a. Langsung DO Reguler dari stok gudang (do_reguler.so_id +
--        do_reguler_items.so_item_id).
--     b. PO dulu (pos.po_jenis = 'so', pos.so_id + po_items.so_item_id) ->
--        Receive Item ke gudang site SO -> stok -> DO Reguler.
--   Qty yang sudah di-PO / di-DO TIDAK disimpan sebagai counter di
--   so_reguler_items -- selalu dihitung dari po_items & do_reguler_items
--   (lihat lib/so-reguler.ts) supaya otomatis benar saat PO ditolak/dihapus
--   atau DO dibatalkan. so_reguler.so_status disegarkan app setelah tiap aksi.
--
-- Backward compat (deploy tidak atomik): cuma tabel baru + kolom nullable +
-- pelonggaran CHECK po_jenis. Code production lama tidak pernah mengisi kolom
-- baru dan tetap jalan apa adanya.

-- ============================================================
-- 1. Header SO
-- ============================================================
CREATE TABLE IF NOT EXISTS public.so_reguler (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    so_kode TEXT UNIQUE NOT NULL,
    so_tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    so_due_date DATE,
    kategori TEXT,
    cabang_id BIGINT NOT NULL REFERENCES public.cabang(id),
    customer_id BIGINT NOT NULL REFERENCES public.customers(id),
    so_pic TEXT,
    so_pic_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    remarks TEXT,

    -- 'open' -> 'partial' -> 'completed' (semua qty sudah ter-DO) | 'cancelled'
    so_status TEXT NOT NULL DEFAULT 'open',

    cancel_reason TEXT,
    cancelled_by UUID,
    cancelled_at TIMESTAMPTZ,

    created_by UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT so_reguler_status_check
      CHECK (so_status IN ('open', 'partial', 'completed', 'cancelled')),
    CONSTRAINT so_reguler_kategori_check
      CHECK (kategori IS NULL OR kategori IN ('New Item', 'Replace Item', 'Fix & Repair', 'Upgrade'))
);

-- ============================================================
-- 2. Item SO
-- ============================================================
CREATE TABLE IF NOT EXISTS public.so_reguler_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    so_id BIGINT NOT NULL REFERENCES public.so_reguler(id) ON DELETE CASCADE,
    part_id BIGINT NOT NULL REFERENCES public.barang(id),
    part_number TEXT NOT NULL,
    part_name TEXT NOT NULL,
    satuan TEXT NOT NULL,
    qty INTEGER NOT NULL CHECK (qty > 0),
    item_priority TEXT NOT NULL DEFAULT 'P3'
      CHECK (item_priority IN ('P1', 'P2', 'P3', 'P4')),
    remarks TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================================
-- 3. Link PO <- SO
-- ============================================================
ALTER TABLE public.pos
  ADD COLUMN IF NOT EXISTS so_id BIGINT REFERENCES public.so_reguler(id);

ALTER TABLE public.po_items
