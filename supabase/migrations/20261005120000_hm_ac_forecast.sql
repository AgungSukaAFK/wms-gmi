ALTER TABLE public.hm_ac_package_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hm_ac_units         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hm_ac_extra_items   ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS hm_ac_packages_read ON public.hm_ac_packages;
CREATE POLICY hm_ac_packages_read ON public.hm_ac_packages FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS hm_ac_package_items_read ON public.hm_ac_package_items;
CREATE POLICY hm_ac_package_items_read ON public.hm_ac_package_items FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS hm_ac_units_read ON public.hm_ac_units;
CREATE POLICY hm_ac_units_read ON public.hm_ac_units FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS hm_ac_extra_items_read ON public.hm_ac_extra_items;
CREATE POLICY hm_ac_extra_items_read ON public.hm_ac_extra_items FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS hm_ac_packages_write ON public.hm_ac_packages;
CREATE POLICY hm_ac_packages_write ON public.hm_ac_packages FOR ALL TO authenticated
  USING (public.hm_is_admin()) WITH CHECK (public.hm_is_admin());
DROP POLICY IF EXISTS hm_ac_package_items_write ON public.hm_ac_package_items;
CREATE POLICY hm_ac_package_items_write ON public.hm_ac_package_items FOR ALL TO authenticated
  USING (public.hm_is_admin()) WITH CHECK (public.hm_is_admin());
DROP POLICY IF EXISTS hm_ac_units_write ON public.hm_ac_units;
CREATE POLICY hm_ac_units_write ON public.hm_ac_units FOR ALL TO authenticated
  USING (public.hm_is_admin()) WITH CHECK (public.hm_is_admin());
DROP POLICY IF EXISTS hm_ac_extra_items_write ON public.hm_ac_extra_items;
CREATE POLICY hm_ac_extra_items_write ON public.hm_ac_extra_items FOR ALL TO authenticated
  USING (public.hm_is_admin()) WITH CHECK (public.hm_is_admin());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.hm_ac_packages      TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.hm_ac_package_items TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.hm_ac_units         TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.hm_ac_extra_items   TO authenticated;
