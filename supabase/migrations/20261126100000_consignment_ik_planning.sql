-- ============================================================
-- Planning IK (Consignment) -- 2026-11-26
--
-- Rencana kirim sebelum Item Konsinyasi (IK) diinput warehouse.
-- PPIC/marketing menyusun 1 dokumen planning per customer (boleh lintas
-- SO / No PO, site tujuan per baris), tanpa approval & tanpa gerak stok.
-- Warehouse lalu membuat IK dari planning (qty IK <= sisa plan); jalur IK
-- langsung dari SO taetap ada.
--
-- Nilai Outstanding / SOH / Sisa Due Date dihitung live di aplikasi,
-- tidak disimpan di sini.
--
-- Backward-compat: hanya tabel baru + kolom NULLABLE di consignment_ik /
-- consignment_ik_items, jadi code production lama tetap jalan.
-- Idempotent (aman di-run ulang).
-- ============================================================

-- 1. Header planning
CREATE TABLE IF NOT EXISTS public.consignment_ik_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_kode TEXT UNIQUE NOT NULL,
    plan_tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    customer_id BIGINT NOT NULL REFERENCES public.customers(id),
    -- Gudang asal rencana kirim (dasar kolom SOH), default GMI-BPP di form.
    dari_cabang_id BIGINT NOT NULL REFERENCES public.cabang(id),
    catatan TEXT,
    -- open = berjalan; closed = ditutup manual (sisa plan tidak dieksekusi).
    -- Progres realisasi (belum/sebagian/selesai) dihitung dari IK.
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    closed_at TIMESTAMPTZ,
    closed_by UUID,
    created_by UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Baris planning (1 baris = 1 item SO ke 1 site)
CREATE TABLE IF NOT EXISTS public.consignment_ik_plan_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES public.consignment_ik_plans(id) ON DELETE CASCADE,
    so_id BIGINT NOT NULL REFERENCES public.consignment_so(id),
    so_item_id BIGINT NOT NULL REFERENCES public.consignment_so_items(id),
    site_id BIGINT NOT NULL REFERENCES public.customer_sites(id),
    site_name TEXT NOT NULL,
    part_id BIGINT NOT NULL REFERENCES public.barang(id),
    part_number TEXT NOT NULL,
    part_name TEXT NOT NULL,
    part_number_customer TEXT,
    satuan TEXT NOT NULL,
    plan_qty INTEGER NOT NULL CHECK (plan_qty > 0),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Link IK -> planning (NULL = IK langsung dari SO / IK lama / import)
ALTER TABLE public.consignment_ik
  ADD COLUMN IF NOT EXISTS plan_id BIGINT REFERENCES public.consignment_ik_plans(id);
ALTER TABLE public.consignment_ik_items
  ADD COLUMN IF NOT EXISTS plan_item_id BIGINT REFERENCES public.consignment_ik_plan_items(id);

COMMENT ON COLUMN public.consignment_ik.plan_id IS
'Planning IK sumber IK ini (NULL = IK dibuat langsung dari SO).';
COMMENT ON COLUMN public.consignment_ik_items.plan_item_id IS
'Baris planning yang direalisasikan item IK ini; realisasi plan = SUM(qty) per plan_item_id.';

-- 4. RLS + grant (tabel baru perlu policy & grant eksplisit)
ALTER TABLE public.consignment_ik_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consignment_ik_plan_items ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow authenticated full access to consignment_ik_plans" ON public.consignment_ik_plans;
CREATE POLICY "Allow authenticated full access to consignment_ik_plans"
  ON public.consignment_ik_plans FOR ALL TO authenticated
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow authenticated full access to consignment_ik_plan_items" ON public.consignment_ik_plan_items;
CREATE POLICY "Allow authenticated full access to consignment_ik_plan_items"
  ON public.consignment_ik_plan_items FOR ALL TO authenticated
  USING (true) WITH CHECK (true);

GRANT ALL ON TABLE public.consignment_ik_plans, public.consignment_ik_plan_items
  TO anon, authenticated, authenticator;

-- 5. Index
CREATE INDEX IF NOT EXISTS idx_consignment_ik_plans_customer ON public.consignment_ik_plans(customer_id);
CREATE INDEX IF NOT EXISTS idx_consignment_ik_plan_items_plan ON public.consignment_ik_plan_items(plan_id);
CREATE INDEX IF NOT EXISTS idx_consignment_ik_plan_items_so_item ON public.consignment_ik_plan_items(so_item_id);
CREATE INDEX IF NOT EXISTS idx_consignment_ik_plan ON public.consignment_ik(plan_id);
CREATE INDEX IF NOT EXISTS idx_consignment_ik_items_plan_item ON public.consignment_ik_items(plan_item_id);

-- 6. updated_at
DROP TRIGGER IF EXISTS update_consignment_ik_plans_modtime ON public.consignment_ik_plans;
CREATE TRIGGER update_consignment_ik_plans_modtime BEFORE UPDATE ON public.consignment_ik_plans
  FOR EACH ROW EXECUTE PROCEDURE update_updated_at_column();

-- 7. Kode planning PIK-00001 (SEQUENCE, race-safe -- pola sama dgn kode IK)
CREATE SEQUENCE IF NOT EXISTS public.consignment_ik_plan_kode_seq;

CREATE OR REPLACE FUNCTION public.generate_consignment_ik_plan_kode()
RETURNS TEXT
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT 'PIK-' || LPAD(nextval('public.consignment_ik_plan_kode_seq')::text, 5, '0');
$$;

GRANT USAGE ON SEQUENCE public.consignment_ik_plan_kode_seq TO authenticated;
GRANT EXECUTE ON FUNCTION public.generate_consignment_ik_plan_kode() TO anon, authenticated, authenticator;
