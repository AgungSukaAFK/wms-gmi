-- Migration: Invoice Konsinyasi (IK) untuk Consignment
-- Date: 2026-09-14
-- Description:
--   IK = dokumen pengiriman fisik barang Consignment dari satu gudang ke
--   gudang lain (Gd Asal -> Gd Tujuan), dengan No AWB. BEDA dari SO
--   Consignment induknya (yang murni pencatatan, tanpa gerak stok & tanpa
--   approval): IK BENAR-BENAR memindahkan stok (potong stok Gd Asal, tambah
--   stok Gd Tujuan) begitu disimpan — satu langkah, TANPA approval,
--   mengikuti pola stock_movements yang sama dengan Delivery/Item Transfer
--   (type 'IK').
--
--   Satu item SO Consignment BISA dikirim lewat lebih dari satu IK
--   (pengiriman sebagian/partial) — makanya item IK adalah tabel terpisah
--   yang merujuk ke consignment_so_items (bukan kolom langsung di situ),
--   supaya histori tiap pengiriman tetap lengkap tersimpan dan Dashboard
--   Consignment bisa menjumlahkan qty terkirim per item.

-- 1. Header
CREATE TABLE IF NOT EXISTS public.consignment_ik (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ik_kode TEXT UNIQUE NOT NULL,
    ik_tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
    so_id BIGINT REFERENCES public.consignment_so(id) NOT NULL,
    dari_cabang_id BIGINT REFERENCES public.cabang(id) NOT NULL,
    ke_cabang_id BIGINT REFERENCES public.cabang(id) NOT NULL,
    no_awb TEXT,
    no_po TEXT,
    remarks TEXT,

    created_by UUID,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT consignment_ik_diff_cabang CHECK (dari_cabang_id <> ke_cabang_id)
);

-- 2. Item lines (1 baris = 1 pengiriman utk 1 item SO; boleh berulang utk
--    item SO yang sama kalau dikirim bertahap/partial)
CREATE TABLE IF NOT EXISTS public.consignment_ik_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ik_id BIGINT REFERENCES public.consignment_ik(id) ON DELETE CASCADE NOT NULL,
    so_item_id BIGINT REFERENCES public.consignment_so_items(id) NOT NULL,
    part_id BIGINT REFERENCES public.barang(id) NOT NULL,
    part_number TEXT NOT NULL,
    part_name TEXT NOT NULL,
    part_number_customer TEXT,
    satuan TEXT NOT NULL,
    qty INTEGER NOT NULL CHECK (qty > 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. RLS (tabel baru perlu policy eksplisit)
ALTER TABLE public.consignment_ik ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consignment_ik_items ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow authenticated full access to consignment_ik" ON public.consignment_ik;
CREATE POLICY "Allow authenticated full access to consignment_ik"
  ON public.consignment_ik FOR ALL TO authenticated
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow authenticated full access to consignment_ik_items" ON public.consignment_ik_items;
CREATE POLICY "Allow authenticated full access to consignment_ik_items"
  ON public.consignment_ik_items FOR ALL TO authenticated
  USING (true) WITH CHECK (true);

-- GRANT eksplisit: tabel baru tidak otomatis dapat privilege dari
