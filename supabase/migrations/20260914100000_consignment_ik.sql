GRANT ALL ON TABLE public.consignment_ik, public.consignment_ik_items
  TO anon, authenticated, authenticator;

-- 4. Index
CREATE INDEX IF NOT EXISTS idx_consignment_ik_so_id ON public.consignment_ik(so_id);
CREATE INDEX IF NOT EXISTS idx_consignment_ik_dari_cabang ON public.consignment_ik(dari_cabang_id);
CREATE INDEX IF NOT EXISTS idx_consignment_ik_ke_cabang ON public.consignment_ik(ke_cabang_id);
CREATE INDEX IF NOT EXISTS idx_consignment_ik_items_ik_id ON public.consignment_ik_items(ik_id);
