-- Pusat Import Excel (moderator): download template & upload data per fitur.
--
-- 1. import_logs: riwayat setiap upload yang diproses (siapa, kapan, file,
--    fitur, jumlah baris baru/update/dilewati/error). Hanya moderator.
-- 2. import_match_barang(text[]): cocokkan part number dari Excel ke master
--    barang dalam 1 panggilan -- persis (abaikan huruf besar/kecil & spasi
--    tepi), lalu "mirip" (abaikan spasi/titik/strip, hanya kalau kandidatnya
--    tunggal). Dipakai semua importer yang punya kolom part number.
-- 3. Index ekspresi upper(btrim(part_number)) untuk pencocokan di atas.
-- 4. import_ref_satuan(): daftar satuan yang dipakai master barang (dropdown).
--
-- Backward compatible: hanya objek baru. Idempotent.

CREATE TABLE IF NOT EXISTS public.import_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feature_key TEXT NOT NULL,
  feature_title TEXT NOT NULL,
  file_name TEXT,
  options JSONB NOT NULL DEFAULT '{}'::jsonb,
  rows_total INT NOT NULL DEFAULT 0,
  rows_created INT NOT NULL DEFAULT 0,
  rows_updated INT NOT NULL DEFAULT 0,
  rows_skipped INT NOT NULL DEFAULT 0,
  rows_error INT NOT NULL DEFAULT 0,
  summary TEXT,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_import_logs_created_at ON public.import_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_import_logs_feature ON public.import_logs (feature_key, created_at DESC);

ALTER TABLE public.import_logs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS import_logs_moderator_select ON public.import_logs;
CREATE POLICY import_logs_moderator_select ON public.import_logs
  FOR SELECT TO authenticated USING (public.is_moderator());
DROP POLICY IF EXISTS import_logs_moderator_insert ON public.import_logs;
CREATE POLICY import_logs_moderator_insert ON public.import_logs
  FOR INSERT TO authenticated WITH CHECK (public.is_moderator());
GRANT SELECT, INSERT ON public.import_logs TO authenticated;

CREATE INDEX IF NOT EXISTS idx_barang_part_number_upper ON public.barang (upper(btrim(part_number)));

CREATE OR REPLACE FUNCTION public.import_match_barang(p_part_numbers TEXT[])
RETURNS TABLE (input TEXT, id BIGINT, part_number TEXT, part_name TEXT, part_satuan TEXT, match TEXT)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  WITH inp AS (
    SELECT DISTINCT x AS input FROM unnest(p_part_numbers) AS x WHERE NULLIF(btrim(x), '') IS NOT NULL
  ),
  exact AS (
    SELECT DISTINCT ON (i.input) i.input, b.id, b.part_number, b.part_name, b.part_satuan, 'persis'::text AS match
    FROM inp i
    JOIN public.barang b ON upper(btrim(b.part_number)) = upper(btrim(i.input))
    ORDER BY i.input, (b.part_number = btrim(i.input)) DESC, b.id
  ),
  loose AS (
    SELECT i.input, min(b.id) AS id, count(*) AS n
    FROM inp i
    JOIN public.barang b
      ON regexp_replace(upper(b.part_number), '[[:space:].-]', '', 'g') = regexp_replace(upper(i.input), '[[:space:].-]', '', 'g')
    WHERE NOT EXISTS (SELECT 1 FROM exact e WHERE e.input = i.input)
    GROUP BY i.input
  )
  SELECT e.input, e.id, e.part_number, e.part_name, e.part_satuan, e.match FROM exact e
  UNION ALL
  SELECT l.input, b.id, b.part_number, b.part_name, b.part_satuan, 'mirip'::text
  FROM loose l JOIN public.barang b ON b.id = l.id
  WHERE l.n = 1;
$$;

GRANT EXECUTE ON FUNCTION public.import_match_barang(TEXT[]) TO authenticated;

-- Daftar satuan yang dipakai di master barang (dropdown template Barang).
CREATE OR REPLACE FUNCTION public.import_ref_satuan()
RETURNS TABLE (satuan TEXT, n BIGINT)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT upper(btrim(part_satuan)) AS satuan, count(*) AS n
  FROM public.barang
  WHERE NULLIF(btrim(part_satuan), '') IS NOT NULL
  GROUP BY 1
  ORDER BY 2 DESC, 1
  LIMIT 300;
$$;

GRANT EXECUTE ON FUNCTION public.import_ref_satuan() TO authenticated;
