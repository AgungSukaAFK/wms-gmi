-- 7. Report view: stok konsinyasi per customer (dipakai halaman "Stok di
--    Customer").
CREATE OR REPLACE VIEW public.v_customer_stock AS
SELECT
    cs.id,
    cs.customer_id,
    c.customer_no,
    c.customer_name,
    cs.part_id,
    b.part_number,
    b.part_name,
    b.part_satuan,
    cs.qty,
    cs.updated_at
FROM public.customer_stock cs
JOIN public.customers c ON c.id = cs.customer_id
JOIN public.barang b ON b.id = cs.part_id
WHERE cs.qty <> 0;
