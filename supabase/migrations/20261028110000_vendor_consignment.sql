-- Cascade delete moderator (_cascade_delete_document_impl) membalik stok IT
-- ke tabel stock biasa. IT konsinyasi yang stoknya sudah keluar tidak boleh
-- ikut terhapus lewat jalur itu (stoknya ada di vendor_consignment_stock).
-- IT yang belum mengeluarkan stok (stock_released = false) tetap boleh
-- dihapus normal.
CREATE OR REPLACE FUNCTION public.guard_consignment_item_transfer_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_kode text;
BEGIN
  IF TG_TABLE_NAME = 'item_transfers' THEN
    IF OLD.it_is_consignment AND OLD.stock_released AND OLD.status::text <> 'completed' THEN
      RAISE EXCEPTION 'Item Transfer konsinyasi % sedang dalam pengiriman (stok konsinyasi sudah keluar) dan tidak bisa dihapus lewat cascade delete. Selesaikan dulu transfernya.', OLD.it_kode;
    END IF;
  ELSE
    SELECT it_kode INTO v_kode FROM public.item_transfers
     WHERE id = OLD.it_id AND it_is_consignment AND stock_released AND status::text <> 'completed';
    IF v_kode IS NOT NULL THEN
      RAISE EXCEPTION 'Item Transfer konsinyasi % sedang dalam pengiriman (stok konsinyasi sudah keluar) dan tidak bisa dihapus lewat cascade delete. Selesaikan dulu transfernya.', v_kode;
    END IF;
  END IF;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_guard_consignment_it_delete ON public.item_transfers;
CREATE TRIGGER trg_guard_consignment_it_delete BEFORE DELETE ON public.item_transfers
  FOR EACH ROW EXECUTE FUNCTION public.guard_consignment_item_transfer_delete();
DROP TRIGGER IF EXISTS trg_guard_consignment_it_item_delete ON public.item_transfer_items;
CREATE TRIGGER trg_guard_consignment_it_item_delete BEFORE DELETE ON public.item_transfer_items
