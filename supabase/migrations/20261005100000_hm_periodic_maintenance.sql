-- Periodic Maintenance (modul "HM Maintenance") — jadwal penggantian part
-- alat berat berdasarkan HM (hour meter). Port dari aplikasi Caffeine
-- "Panel Kontrol — Periodic Maintenance", spesifikasi lengkap di hm.md.
--
-- Penyesuaian terhadap spec (hm.md §10) untuk WMS-GMI:
--   - Baca: semua user login (authenticated), bukan publik/anon.
--   - Tulis ("admin" modul): moderator ATAU role "service", lewat
--     hm_is_admin(). Tidak ada tabel hm_admins.
--   - Unit punya gudang (hm_units.cabang_id, opsional).
--   - Part bisa di-link ke master barang (hm_parts.barang_id, opsional).
--     Kolom manual stock_on_hand dari spec DIGANTI stok WMS: stok barang di
--     gudang unit, atau total semua gudang kalau unit belum punya gudang.
--   - Catat penggantian bisa memotong stok WMS (qty_used) di gudang unit,
--     atomic di RPC hm_record_replacement + tercatat di stock_movements
--     (type 'HM_REPLACEMENT').
--
-- Semua objek baru (prefix hm_), tidak mengubah tabel lama -> aman untuk
-- build production lama. Idempotent.

-- ============================================================
-- 1. Helper admin modul
-- ============================================================

CREATE OR REPLACE FUNCTION public.hm_is_admin()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.user_roles ur
    JOIN public.roles r ON ur.role_id = r.id
    WHERE ur.user_id = auth.uid() AND r.name IN ('moderator', 'service')
  );
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public;

GRANT EXECUTE ON FUNCTION public.hm_is_admin() TO authenticated;

