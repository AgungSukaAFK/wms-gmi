CREATE TABLE IF NOT EXISTS public.hm_units (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        TEXT    NOT NULL,
  name        TEXT    NOT NULL,
  model       TEXT    NOT NULL,
  current_hm  INTEGER NOT NULL DEFAULT 0 CHECK (current_hm >= 0),
  -- Gudang unit: sumber stok part & tempat stok dipotong saat penggantian.
  cabang_id   BIGINT REFERENCES public.cabang(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.hm_parts (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_id             BIGINT  NOT NULL REFERENCES public.hm_units(id) ON DELETE CASCADE,
  barang_id           BIGINT  REFERENCES public.barang(id) ON DELETE SET NULL,
  code                TEXT    NOT NULL,
  name                TEXT    NOT NULL,
  -- >= 0 (bukan > 0) supaya setara backend asli; "> 0" ditegakkan form.
  interval_hm         INTEGER NOT NULL CHECK (interval_hm >= 0),
  last_replacement_hm INTEGER NOT NULL CHECK (last_replacement_hm >= 0),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS hm_parts_unit_id_idx ON public.hm_parts(unit_id);
CREATE INDEX IF NOT EXISTS hm_parts_barang_id_idx ON public.hm_parts(barang_id);

CREATE TABLE IF NOT EXISTS public.hm_replacements (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  part_id    BIGINT  NOT NULL REFERENCES public.hm_parts(id) ON DELETE CASCADE,
  unit_id    BIGINT  NOT NULL REFERENCES public.hm_units(id) ON DELETE CASCADE,
  hm         INTEGER NOT NULL CHECK (hm >= 0),
  date       TIMESTAMPTZ NOT NULL,
  note       TEXT    NOT NULL DEFAULT '',
  -- Qty barang yang dipotong dari stok WMS (0 = tidak memotong stok).
  qty_used   INTEGER NOT NULL DEFAULT 0 CHECK (qty_used >= 0),
  cabang_id  BIGINT REFERENCES public.cabang(id) ON DELETE SET NULL,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS hm_replacements_part_hm_idx ON public.hm_replacements(part_id, hm);
CREATE INDEX IF NOT EXISTS hm_replacements_unit_id_idx ON public.hm_replacements(unit_id);

