-- Migration: perbaikan hasil audit qty & status lintas dokumen (2026-10-15).
-- Additive only -> aman untuk deploy tidak atomik (code lama tidak membaca
-- tabel baru ini, code baru menganggap tabel kosong bila belum ada).
--
-- 1. mr_sharestock_bypasses: jejak qty yang dipindah lewat "Bypass share
--    stock" per (mr_item, gudang sumber). Sebelumnya bypass cuma mencatat
--    stock_movements, sehingga sisa alokasi share stock bisa muncul lagi
--    (dan di-bypass dua kali) dan qty bypass tidak pernah dihitung ke
--    pemenuhan MR (mr_items.qty_received).
-- 2. Backfill dari stock_movements bypass lama (reference_id 'BYPASS-<mr_kode>').
-- 3. Status SPB: 'DONE_QUOTE' disamakan jadi 'DONE QUOT', dan SPB yang
--    statusnya tertimpa 'Partial' oleh retur parsial dikembalikan ke status
--    progres PO/DO/Invoice-nya.

CREATE TABLE IF NOT EXISTS public.mr_sharestock_bypasses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mr_item_id BIGINT NOT NULL REFERENCES public.mr_items(id) ON DELETE CASCADE,
    source_cabang_id BIGINT NOT NULL REFERENCES public.cabang(id),
    qty INTEGER NOT NULL CHECK (qty > 0),
    reference_id TEXT,
    note TEXT,
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_mr_sharestock_bypasses_mr_item_id
  ON public.mr_sharestock_bypasses(mr_item_id);

COMMENT ON TABLE public.mr_sharestock_bypasses IS
  'Qty share stock yang dipindah lewat Bypass (moderator), per gudang sumber. Dihitung sebagai alokasi terkirim (sisa share stock) dan pemenuhan MR (lib/mr-fulfillment.ts).';

ALTER TABLE public.mr_sharestock_bypasses ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow authenticated full access to mr_sharestock_bypasses" ON public.mr_sharestock_bypasses;
CREATE POLICY "Allow authenticated full access to mr_sharestock_bypasses"
  ON public.mr_sharestock_bypasses FOR ALL TO authenticated
  USING (true) WITH CHECK (true);

GRANT ALL ON TABLE public.mr_sharestock_bypasses TO authenticated, service_role;

-- Backfill: baris keluar (qty_change < 0) bypass lama per gudang sumber.
-- Item MR dicocokkan lewat mr_kode + part_id (ambil item dengan id terkecil
-- kalau PN sama muncul lebih dari sekali di MR yang sama). Idempotent.
INSERT INTO public.mr_sharestock_bypasses (mr_item_id, source_cabang_id, qty, reference_id, note, created_by, created_at)
SELECT
  mi.id,
  sm.cabang_id,
  -SUM(sm.qty_change)::INTEGER,
  sm.reference_id,
  'Backfill dari stock_movements bypass lama',
  NULL,
  MIN(sm.created_at)
FROM public.stock_movements sm
JOIN public.mrs m
  ON sm.reference_id = 'BYPASS-' || m.mr_kode
JOIN LATERAL (
  SELECT mi2.id
  FROM public.mr_items mi2
  WHERE mi2.mr_id = m.id AND mi2.part_id = sm.part_id
  ORDER BY mi2.id
  LIMIT 1
) mi ON TRUE
WHERE sm.type = 'SS'
  AND sm.reference_id LIKE 'BYPASS-%'
  AND sm.qty_change < 0
  AND sm.cabang_id <> m.cabang_id
  AND NOT EXISTS (
    SELECT 1 FROM public.mr_sharestock_bypasses b
    WHERE b.mr_item_id = mi.id AND b.source_cabang_id = sm.cabang_id
  )
GROUP BY mi.id, sm.cabang_id, sm.reference_id
HAVING SUM(sm.qty_change) < 0;

-- Status SPB.
UPDATE public.spb SET spb_status = 'DONE QUOT' WHERE spb_status = 'DONE_QUOTE';

UPDATE public.spb s
SET spb_status = CASE
  WHEN EXISTS (
    SELECT 1 FROM public.spb_invoice i
    JOIN public.spb_do d ON d.id = i.spb_do_id
    JOIN public.spb_po p ON p.id = d.spb_po_id
    WHERE p.spb_id = s.id AND i.approval_status = 'completed'
  ) THEN 'DONE QUOT'
  WHEN EXISTS (
    SELECT 1 FROM public.spb_do d
    JOIN public.spb_po p ON p.id = d.spb_po_id
    WHERE p.spb_id = s.id
  ) THEN 'DO_ATTACH'
  WHEN EXISTS (SELECT 1 FROM public.spb_po p WHERE p.spb_id = s.id) THEN 'PO_ATTACH'
  ELSE 'DONE QUOT'
END
WHERE s.spb_status = 'Partial';
