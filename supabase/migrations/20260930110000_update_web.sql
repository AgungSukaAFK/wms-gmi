-- Update Web: changelog/pengumuman aplikasi untuk SEMUA user login.
--
-- Menggantikan /update-logs (changelog sederhana yang cuma bisa dilihat
-- moderator+it). Diadaptasi dari fitur "Update Web" di ga-web, dengan
-- penyesuaian ke RBAC repo ini (user_roles, bukan profiles.role):
--   - Baca, reaction, komentar: semua user login.
--   - Buat/edit/hapus post + upload media: moderator yang JUGA punya role
--     "it" (sama dengan penjaga /update-logs sebelumnya).
--
-- Isi:
--   1. Helper is_update_web_publisher()
--   2. Tabel update_web_posts (versi x.y.z = 3 kolom int + generated text)
--   3. Tabel update_web_post_reactions (1 emoji aktif per user per post)
--   4. Tabel update_web_seen (badge "update baru", per akun lintas device)
--   5. RPC create_update_web_post (penomoran versi atomic)
--   6. RPC add_update_web_post_comment (komentar teks, semua user)
--   7. Storage bucket "update-web" (thumbnail + media body)
--   8. Migrasi data update_logs -> update_web_posts
--
-- BACKWARD-COMPAT: tabel update_logs & kolom profiles.last_seen_update_log_at
-- SENGAJA tidak dihapus, supaya build production lama (/update-logs) tetap
-- jalan selama deploy frontend belum selesai. Semua langkah idempotent.

-- ============================================================
-- 1. Helper: siapa yang boleh publish
-- ============================================================

CREATE OR REPLACE FUNCTION public.is_update_web_publisher()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN public.is_moderator() AND public.is_it();
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public;

GRANT EXECUTE ON FUNCTION public.is_update_web_publisher() TO authenticated;

-- ============================================================
-- 2. update_web_posts
-- ============================================================

CREATE TABLE IF NOT EXISTS public.update_web_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_major INT NOT NULL CHECK (version_major >= 0),
  version_minor INT NOT NULL CHECK (version_minor >= 0),
  version_patch INT NOT NULL CHECK (version_patch >= 0),
  -- Generated supaya string versi tidak mungkin beda dari 3 kolom int-nya.
  version TEXT GENERATED ALWAYS AS (
    version_major::text || '.' || version_minor::text || '.' || version_patch::text
  ) STORED,
  title TEXT NOT NULL,
  thumbnail_url TEXT,
  -- Ringkasan poin singkat (string[]) untuk card & bagian atas detail.
  highlights JSONB NOT NULL DEFAULT '[]'::jsonb,
  -- Body rich text, format Tiptap JSON doc.
  content JSONB NOT NULL DEFAULT '{}'::jsonb,
  -- Komentar append-only: [{user_id, user_name, message, timestamp}],
  -- hanya diisi lewat RPC add_update_web_post_comment.
  comments JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (version_major, version_minor, version_patch)
);

CREATE INDEX IF NOT EXISTS idx_update_web_posts_created_at
  ON public.update_web_posts (created_at DESC);

DROP TRIGGER IF EXISTS update_update_web_posts_modtime ON public.update_web_posts;
CREATE TRIGGER update_update_web_posts_modtime
  BEFORE UPDATE ON public.update_web_posts
  FOR EACH ROW EXECUTE PROCEDURE update_updated_at_column();

ALTER TABLE public.update_web_posts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "update_web_posts_select" ON public.update_web_posts;
CREATE POLICY "update_web_posts_select"
  ON public.update_web_posts FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "update_web_posts_insert_publisher" ON public.update_web_posts;
CREATE POLICY "update_web_posts_insert_publisher"
  ON public.update_web_posts FOR INSERT TO authenticated
  WITH CHECK (public.is_update_web_publisher());

DROP POLICY IF EXISTS "update_web_posts_update_publisher" ON public.update_web_posts;
CREATE POLICY "update_web_posts_update_publisher"
  ON public.update_web_posts FOR UPDATE TO authenticated
  USING (public.is_update_web_publisher())
  WITH CHECK (public.is_update_web_publisher());

DROP POLICY IF EXISTS "update_web_posts_delete_publisher" ON public.update_web_posts;
CREATE POLICY "update_web_posts_delete_publisher"
  ON public.update_web_posts FOR DELETE TO authenticated
  USING (public.is_update_web_publisher());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.update_web_posts TO authenticated;

