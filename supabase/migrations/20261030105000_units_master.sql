CREATE TABLE IF NOT EXISTS public.units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_unit TEXT NOT NULL CHECK (BTRIM(kode_unit) <> ''),
    -- Wajib: unit tanpa tipe terdaftar (ERP "(blank)"/"NOT REGISTERED") tidak dipakai.
    tipe_unit TEXT NOT NULL CHECK (BTRIM(tipe_unit) <> ''),
    -- HURUF BESAR (KOMATSU, MERCEDES-BENZ, ...) senada data SPB lama; NULL = belum diketahui.
    brand TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_units_kode_unit
  ON public.units ((UPPER(kode_unit)));
CREATE INDEX IF NOT EXISTS idx_units_tipe_unit ON public.units (tipe_unit);
CREATE INDEX IF NOT EXISTS idx_units_brand ON public.units (brand);

ALTER TABLE public.units ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated can read units" ON public.units;
CREATE POLICY "Authenticated can read units"
  ON public.units FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "Moderator can insert units" ON public.units;
CREATE POLICY "Moderator can insert units"
  ON public.units FOR INSERT TO authenticated
  WITH CHECK (public.is_moderator());

DROP POLICY IF EXISTS "Moderator can update units" ON public.units;
CREATE POLICY "Moderator can update units"
  ON public.units FOR UPDATE TO authenticated
  USING (public.is_moderator()) WITH CHECK (public.is_moderator());

DROP POLICY IF EXISTS "Moderator can delete units" ON public.units;
CREATE POLICY "Moderator can delete units"
  ON public.units FOR DELETE TO authenticated
  USING (public.is_moderator());

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.units TO authenticated;

DROP TRIGGER IF EXISTS update_units_modtime ON public.units;
CREATE TRIGGER update_units_modtime BEFORE UPDATE ON public.units
  FOR EACH ROW EXECUTE PROCEDURE update_updated_at_column();
