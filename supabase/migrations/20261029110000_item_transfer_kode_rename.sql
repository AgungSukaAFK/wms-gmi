-- Kode Item Transfer bisa diubah moderator kapan pun (termasuk setelah stok
-- keluar / IT selesai). Dokumen lain mereferensikan IT lewat TEKS kode-nya,
-- bukan id:
--   - stock_movements.reference_id              (type 'IT')
--   - vendor_consignment_movements.reference_id (type 'IT_OUT' / 'IT_IN')
-- Trigger di bawah merambatkan kode baru ke referensi tersebut di transaksi
-- yang SAMA dengan UPDATE item_transfers.it_kode (atomik, berlaku untuk jalur
-- edit mana pun), lalu mencatat riwayatnya di item_transfer_kode_history.
-- Kolom notes di stock_movements sengaja tidak diubah (teks historis).
--
-- Additive: tabel baru + trigger; kode production lama tidak terpengaruh.

CREATE TABLE IF NOT EXISTS public.item_transfer_kode_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  it_id BIGINT NOT NULL REFERENCES public.item_transfers(id) ON DELETE CASCADE,
  old_kode TEXT NOT NULL,
  new_kode TEXT NOT NULL,
  stock_movements_updated INTEGER NOT NULL DEFAULT 0,
  consignment_movements_updated INTEGER NOT NULL DEFAULT 0,
  -- Sengaja tanpa FK: rename lewat SQL Editor (auth.uid() NULL) atau user
  -- tanpa profil tidak boleh menggagalkan perubahan kode.
  changed_by UUID,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_item_transfer_kode_history_it
  ON public.item_transfer_kode_history (it_id, changed_at DESC);
CREATE INDEX IF NOT EXISTS idx_item_transfer_kode_history_old_kode
  ON public.item_transfer_kode_history (old_kode);

ALTER TABLE public.item_transfer_kode_history ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Authenticated can read item_transfer_kode_history"
  ON public.item_transfer_kode_history;
CREATE POLICY "Authenticated can read item_transfer_kode_history"
  ON public.item_transfer_kode_history FOR SELECT TO authenticated USING (true);
-- Tidak ada policy INSERT: baris hanya ditulis trigger (SECURITY DEFINER).

CREATE OR REPLACE FUNCTION public.propagate_item_transfer_kode()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_stock integer := 0;
  v_consignment integer := 0;
BEGIN
  UPDATE public.stock_movements
     SET reference_id = NEW.it_kode
   WHERE type = 'IT' AND reference_id = OLD.it_kode;
  GET DIAGNOSTICS v_stock = ROW_COUNT;

  -- Dinamis supaya migration ini tetap jalan di DB yang belum punya modul
  -- konsinyasi vendor (20261028110000).
  IF to_regclass('public.vendor_consignment_movements') IS NOT NULL THEN
    EXECUTE 'UPDATE public.vendor_consignment_movements
                SET reference_id = $1
              WHERE type IN (''IT_OUT'', ''IT_IN'') AND reference_id = $2'
      USING NEW.it_kode, OLD.it_kode;
    GET DIAGNOSTICS v_consignment = ROW_COUNT;
  END IF;

  INSERT INTO public.item_transfer_kode_history
    (it_id, old_kode, new_kode, stock_movements_updated, consignment_movements_updated, changed_by)
  VALUES
    (NEW.id, OLD.it_kode, NEW.it_kode, v_stock, v_consignment, auth.uid());

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_propagate_item_transfer_kode ON public.item_transfers;
CREATE TRIGGER trg_propagate_item_transfer_kode
  AFTER UPDATE OF it_kode ON public.item_transfers
  FOR EACH ROW
  WHEN (OLD.it_kode IS DISTINCT FROM NEW.it_kode)
  EXECUTE FUNCTION public.propagate_item_transfer_kode();
